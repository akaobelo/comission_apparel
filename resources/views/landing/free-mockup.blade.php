(function(){
  // Organization Type button selection
  var btns = document.querySelectorAll('.org-btn');
  var orgInput = document.getElementById('orgType');
  function pick(b){
    btns.forEach(function(x){ x.classList.toggle('on', x === b); });
    if(orgInput && b) { orgInput.value = b.getAttribute('data-org'); }
  }
  btns.forEach(function(b){
    b.addEventListener('click', function(){ pick(b); });
  });

  // UTM Parameter capture from URL & SessionStorage
  var urlParams = new URLSearchParams(window.location.search);
  var utms = ['utm_source', 'utm_medium', 'utm_campaign', 'utm_term', 'utm_content'];
  utms.forEach(function(param){
    var val = urlParams.get(param);
    if(val){
      try { sessionStorage.setItem(param, val); } catch(e){}
      var el = document.getElementById(param);
      if(el) el.value = val;
    } else {
      try {
        var saved = sessionStorage.getItem(param);
        var el = document.getElementById(param);
        if(saved && el) el.value = saved;
      } catch(e){}
    }
  });

  // Form Submission via AJAX (with fallback)
  var form = document.getElementById('leadForm');
  var thanks = document.getElementById('thanks');
  var submitBtn = document.getElementById('submitBtn');
  var btnText = document.getElementById('btnText');
  var formError = document.getElementById('formError');

  form.addEventListener('submit', function(e){
    e.preventDefault();
    if(formError) formError.style.display = 'none';

    var formData = new FormData(form);
    var data = {};
    formData.forEach(function(value, key){
      data[key] = value;
    });

    // Disable button while processing
    if(submitBtn) {
      submitBtn.disabled = true;
      submitBtn.style.opacity = '0.7';
    }
    if(btnText) btnText.textContent = 'Submitting...';

    fetch(form.action, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Accept': 'application/json',
        'X-Requested-With': 'XMLHttpRequest'
      },
      body: JSON.stringify(data)
    })
    .then(function(res){
      if(!res.ok){
        return res.json().then(function(json){
          var msg = json.message || 'Submission failed. Please check the fields and try again.';
          if(json.errors) {
            var firstKey = Object.keys(json.errors)[0];
            if(firstKey && json.errors[firstKey][0]) {
              msg = json.errors[firstKey][0];
            }
          }
          throw new Error(msg);
        });
      }
      return res.json();
    })
    .then(function(result){
      // 1. Fire Meta Pixel Lead event ONLY on verified successful submission
      if(typeof window.fbq === 'function'){
        try {
          window.fbq('track', 'Lead');
        } catch(err){
          console.warn('Meta Pixel tracking error:', err);
        }
      }

      // 2. Display thank-you screen
      form.style.display = 'none';
      thanks.style.display = 'flex';
      thanks.scrollIntoView({ behavior: 'smooth', block: 'center' });
    })
    .catch(function(err){
      if(formError){
        formError.textContent = err.message || 'There was an issue submitting your request. Please try again.';
        formError.style.display = 'block';
      } else {
        alert(err.message || 'There was an issue submitting your request.');
      }
    })
    .finally(function(){
      if(submitBtn) {
        submitBtn.disabled = false;
        submitBtn.style.opacity = '1';
      }
      if(btnText) btnText.textContent = 'Get my free mockup';
    });
  });

  // Reset button to submit another program
  document.getElementById('resetBtn').addEventListener('click', function(){
    form.reset();
    form.style.display = 'flex';
    thanks.style.display = 'none';
    if(btns[0]) pick(btns[0]);
    // Re-populate UTMs into form inputs
    utms.forEach(function(param){
      try {
        var saved = sessionStorage.getItem(param);
        var el = document.getElementById(param);
        if(saved && el) el.value = saved;
      } catch(e){}
    });
  });
})();
